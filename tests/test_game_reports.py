"""Game reports: the shared game key.

The key names a game in every report and in Wayfinder's server-side catalog
(generated by scripts/export_game_catalog.py), so it must be stable, valid and
unique across the macOS, Windows and Linux Games-tab lists.
Design: docs/plans/game-reports-design-2026-10-15.md, section 5.1.
"""

from __future__ import annotations

import pytest

from wayfinder.core import linux_game_chat, macos_game_chat, windows_game_chat
from wayfinder.core.game_reports import GAME_KEY_MAX, game_key, is_valid_game_key


@pytest.mark.parametrize("name,key", [
    ("World of Warcraft", "world-of-warcraft"),
    ("Garry's Mod", "garrys-mod"),
    ("Sid Meier’s Civilization VI", "sid-meiers-civilization-vi"),
    ("Don't Starve Together", "dont-starve-together"),
    ("Pokémon Unite", "pokemon-unite"),
    ("Firestone – Idle Clicker Online RPG", "firestone-idle-clicker-online-rpg"),
    ("Age of Empires II: Definitive Edition", "age-of-empires-ii-definitive-edition"),
    ("Cloud gaming (GeForce NOW, Xbox Cloud, Boosteroid)",
     "cloud-gaming-geforce-now-xbox-cloud-boosteroid"),
    ("  7 Days to Die  ", "7-days-to-die"),
    ("Foo–Bar", "foo-bar"),
])
def test_game_key_folds_a_name_to_a_slug(name, key):
    assert game_key(name) == key


def test_game_key_caps_at_64_characters_without_a_trailing_dash():
    assert game_key("a" * 100) == "a" * GAME_KEY_MAX
    long_words = game_key("word " * 30)
    assert len(long_words) <= GAME_KEY_MAX
    assert is_valid_game_key(long_words)


def test_nfkd_compatibility_forms_fold_to_ascii():
    assert game_key("Game™") == "gametm"        # NFKD spells the trademark sign TM
    assert game_key("ＧＡＭＥ") == "game"  # full-width letters


def test_a_name_without_ascii_letters_or_digits_has_no_valid_key():
    assert game_key(" – !! ") == ""
    assert game_key("ファイナル") == ""
    assert not is_valid_game_key("")
    assert not is_valid_game_key("-lead")
    assert not is_valid_game_key("Upper")
    assert not is_valid_game_key("a" * (GAME_KEY_MAX + 1))


def _lists():
    return {
        "macos": [e.name for e in macos_game_chat.game_list()],
        "windows": [e.name for e in windows_game_chat.game_list()],
        "linux": [e.name for e in linux_game_chat.game_list()],
    }


def test_every_listed_game_has_a_valid_key_unique_in_its_list():
    for system, names in _lists().items():
        keys = [game_key(n) for n in names]
        assert all(is_valid_game_key(k) for k in keys), system
        assert len(keys) == len(set(keys)), system


def test_one_key_never_names_two_games_across_the_lists():
    names_by_key: dict[str, set[str]] = {}
    for names in _lists().values():
        for name in names:
            names_by_key.setdefault(game_key(name), set()).add(name)
    assert {k: v for k, v in names_by_key.items() if len(v) > 1} == {}


# The profile games' keys are what reports and the server catalog use; a
# rename here would orphan every report already sent for the game.
PINNED_PROFILE_KEYS = {
    "World of Warcraft": "world-of-warcraft",
    "Final Fantasy XIV": "final-fantasy-xiv",
    "The Elder Scrolls Online": "the-elder-scrolls-online",
    "The Lord of the Rings Online": "the-lord-of-the-rings-online",
    "Albion Online": "albion-online",
    "Path of Exile": "path-of-exile",
    "EVE Online": "eve-online",
    "RuneScape": "runescape",
    "League of Legends": "league-of-legends",
    "Black Desert": "black-desert",
    "Dark Age of Camelot": "dark-age-of-camelot",
}


def test_profile_game_keys_are_pinned():
    profiles = {p.name for p in linux_game_chat.PROFILES}
    assert profiles == set(PINNED_PROFILE_KEYS)
    assert {name: game_key(name) for name in profiles} == PINNED_PROFILE_KEYS
