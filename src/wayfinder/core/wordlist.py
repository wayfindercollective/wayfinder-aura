"""English word-frequency tiers for voice-profile vocabulary extraction.

The words live in wordlist.txt beside this module, generated by
scripts/gen_wordlists.py from the Google Web Trillion Word Corpus counts
published by Peter Norvig (https://norvig.com/ngrams/count_1w.txt). Cutoffs:
STOP = corpus rank <= 3000, MID = rank 3001..20000, COMMON = rank
20001..60000; 3+ letter alphabetic words only (the tokenizer never emits
shorter tokens). Words in none of the sets are the distinctive tail — names,
jargon, mishearings — exactly what a personality profile wants.
"""

from pathlib import Path

DATA_FILE = Path(__file__).with_name("wordlist.txt")


def _load_tiers(path: Path = DATA_FILE) -> dict[str, frozenset[str]]:
    tiers: dict[str, list[str]] = {}
    words = None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("[") and line.endswith("]"):
                words = tiers.setdefault(line[1:-1], [])
            elif words is None:
                raise ValueError(f"{path.name}: words before the first [tier] header")
            else:
                words.extend(line.split())
    return {name: frozenset(found) for name, found in tiers.items()}


_TIERS = _load_tiers()

# rank <= 3000: ordinary English — never vocabulary, no matter how often said.
STOP_WORDS = _TIERS["stop"]
# rank 3001..20000: common-ish — needs heavy repetition to surface.
MID_WORDS = _TIERS["mid"]
# rank 20001..60000: still real English. Vocabulary near-miss snapping
# (transcriber.snap_near_vocabulary) never respells these.
COMMON_WORDS = _TIERS["common"]
