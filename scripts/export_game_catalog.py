#!/usr/bin/env python3
"""Print Wayfinder OS's game catalog for Aura game reports (gameCatalog.ts).

The server accepts a game report only for a game and an Aura version line it
knows. Both lists come from this repository and are committed in Wayfinder OS
as ``convex/auraDesktop/gameCatalog.ts`` (design
docs/plans/game-reports-design-2026-10-15.md, section 5.5):

* ``AURA_GAME_CATALOG``: every game on the macOS, Windows and Linux Games-tab
  lists (``game_list()``), as sorted ``{key, name}`` pairs, keyed by
  ``wayfinder.core.game_reports.game_key()``.
* ``AURA_RELEASE_LINES``: the sorted ``major.minor`` of every ``vX.Y.Z`` or
  ``vX.Y.Z-pre`` release tag. Other tags (``macos-preview-*``, ``archive/*``)
  are ignored. Tagging a release is the owner's act, so a tagged line is
  trusted.
* ``RELEASE_LINES_VERSION``: a short hash of that list.

The output is deterministic and names the Aura commit it was made from. The
script exits 1, printing nothing, on a duplicate key, a key with two names, a
name with no usable key, or no release tags.

    python scripts/export_game_catalog.py > gameCatalog.ts
    python scripts/export_game_catalog.py --no-fetch   # use the tags already here

Run it on an up-to-date ``origin/main``. It fetches tags from ``origin`` first
unless told not to. It sends nothing else anywhere.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from collections.abc import Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from wayfinder.core.game_reports import game_key, is_valid_game_key  # noqa: E402

# vX.Y.Z or vX.Y.Z-<pre-release> (v1.2.1-beta.4); nothing else counts.
_RELEASE_TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z][0-9A-Za-z.-]*)?$")


class CatalogError(Exception):
    """The game lists can't make a one-to-one catalog."""


def game_name_lists() -> dict[str, list[str]]:
    """Each system's Games-tab names, as the app spells them."""
    from wayfinder.core import linux_game_chat, macos_game_chat, windows_game_chat

    return {
        "macos": [e.name for e in macos_game_chat.game_list()],
        "windows": [e.name for e in windows_game_chat.game_list()],
        "linux": [e.name for e in linux_game_chat.game_list()],
    }


def build_catalog(lists: dict[str, list[str]]) -> list[tuple[str, str]]:
    """Sorted (key, name) pairs for the union of the lists, one per game."""
    names_by_key: dict[str, str] = {}
    for system, names in lists.items():
        seen: dict[str, str] = {}
        for name in names:
            key = game_key(name)
            if not is_valid_game_key(key):
                raise CatalogError(f"{system} list: {name!r} has no usable key")
            if key in seen:
                raise CatalogError(
                    f"duplicate key {key!r} in the {system} list: {seen[key]!r} and {name!r}")
            seen[key] = name
            known = names_by_key.setdefault(key, name)
            if known != name:
                raise CatalogError(f"key {key!r} has two names: {known!r} and {name!r}")
    return sorted(names_by_key.items())


def release_lines(tags: Iterable[str]) -> list[str]:
    """The ``major.minor`` lines with a release tag, sorted numerically."""
    lines = set()
    for tag in tags:
        match = _RELEASE_TAG.match(tag.strip())
        if match:
            lines.add((int(match[1]), int(match[2])))
    return [f"{major}.{minor}" for major, minor in sorted(lines)]


def release_lines_version(lines: list[str]) -> str:
    """A short, stable fingerprint of the release-line list."""
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()[:12]


def _literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render(catalog: list[tuple[str, str]], lines: list[str], sha: str) -> str:
    out = [
        f"// Generated by wayfinder-aura `scripts/export_game_catalog.py` at {sha}; do not edit.",
        "// Regenerate from an up-to-date wayfinder-aura origin/main (tags fetched):",
        "//   python scripts/export_game_catalog.py > convex/auraDesktop/gameCatalog.ts",
        "// Games: the union of Aura's macOS, Windows and Linux Games-tab lists, keyed",
        "// by game_key(). Release lines: the major.minor of every vX.Y.Z or vX.Y.Z-pre tag.",
        "",
        "export const AURA_GAME_CATALOG: ReadonlyArray<{ key: string; name: string }> = [",
    ]
    out += [f"  {{ key: {_literal(key)}, name: {_literal(name)} }}," for key, name in catalog]
    out += [
        "];",
        "",
        "export const AURA_RELEASE_LINES: ReadonlyArray<string> = [",
    ]
    out += [f"  {_literal(line)}," for line in lines]
    out += [
        "];",
        "",
        f"export const RELEASE_LINES_VERSION = {_literal(release_lines_version(lines))};",
    ]
    return "\n".join(out) + "\n"


def _git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                          check=True, timeout=120).stdout


def _source_sha() -> str:
    sha = _git("rev-parse", "HEAD").strip()
    dirty = _git("status", "--porcelain", "--untracked-files=no").strip()
    return f"{sha}-dirty" if dirty else sha


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--no-fetch", action="store_true",
                        help="use the tags already in this checkout")
    parser.add_argument("--remote", default="origin", help="where to fetch tags from")
    parser.add_argument("--tags-file", type=Path,
                        help="read tags from this file (one per line) instead of git")
    args = parser.parse_args(argv)

    def fail(message: str) -> int:
        print(f"export_game_catalog: {message}", file=sys.stderr)
        return 1

    try:
        catalog = build_catalog(game_name_lists())
    except CatalogError as exc:
        return fail(str(exc))
    try:
        if args.tags_file is not None:
            tags = args.tags_file.read_text(encoding="utf-8").splitlines()
        else:
            if not args.no_fetch:
                _git("fetch", "--tags", "--quiet", args.remote)
            tags = _git("tag", "--list").splitlines()
        sha = _source_sha()
    except (OSError, subprocess.SubprocessError) as exc:
        return fail(f"could not read the repository: {exc}")
    lines = release_lines(tags)
    if not lines:
        return fail("no vX.Y.Z release tags found (fetch the tags first)")
    # UTF-8 with LF line ends on every system, so the file is the same everywhere.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    sys.stdout.write(render(catalog, lines, sha))
    return 0


if __name__ == "__main__":
    sys.exit(main())
